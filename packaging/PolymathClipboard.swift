private struct Clip: Codable, Identifiable, Equatable {
    let id: String
    var kind: String
    var title: String
    var text: String?
    var files: [String]?
    var imageName: String?
    var source: String
    var copiedAt: Date
    var pinned: Bool

    var searchable: String { "\(title) \(text ?? "") \(source)" }
}

private final class ClipLibrary: ObservableObject {
    @Published private(set) var clips: [Clip] = []
    @Published var selectedID: String?
    @Published var query = ""
    @Published var filter = "All"
    @Published var notice = ""

    private let folder: URL
    private let imageFolder: URL
    private let index: URL
    private var lastChange: Int
    private let encoder = JSONEncoder()
    private let decoder = JSONDecoder()

    init(folder: URL, pasteboard: NSPasteboard = .general) {
        self.folder = folder
        imageFolder = folder.appendingPathComponent("Images", isDirectory: true)
        index = folder.appendingPathComponent("history.json")
        lastChange = pasteboard.changeCount
        encoder.dateEncodingStrategy = .iso8601
        decoder.dateDecodingStrategy = .iso8601
        if let bytes = try? Data(contentsOf: index),
           let saved = try? decoder.decode([Clip].self, from: bytes) {
            clips = Array(saved.prefix(400))
            selectedID = clips.first?.id
        }
    }

    var selected: Clip? { clips.first { $0.id == selectedID } }
    var pinned: [Clip] { visible.filter(\.pinned) }
    var recent: [Clip] { visible.filter { !$0.pinned } }
    var count: Int { clips.count }

    private var visible: [Clip] {
        let word = query.trimmingCharacters(in: .whitespacesAndNewlines)
        return clips.filter { clip in
            (filter == "All" || clip.kind == filter)
                && (word.isEmpty || clip.searchable.localizedCaseInsensitiveContains(word))
        }
    }

    func selectFirstVisible() {
        if !visible.contains(where: { $0.id == selectedID }) {
            selectedID = visible.first?.id
        }
    }

    func moveSelection(_ step: Int) {
        let rows = visible
        guard !rows.isEmpty else { return }
        let current = rows.firstIndex(where: { $0.id == selectedID }) ?? 0
        selectedID = rows[min(max(current + step, 0), rows.count - 1)].id
    }

    func capture(_ board: NSPasteboard = .general) {
        guard board.changeCount != lastChange else { return }
        lastChange = board.changeCount
        let types = board.types ?? []
        let hidden = ["org.nspasteboard.TransientType", "org.nspasteboard.ConcealedType",
                      "org.nspasteboard.AutoGeneratedType"]
        if hidden.contains(where: { types.contains(NSPasteboard.PasteboardType($0)) }) { return }
        let application = NSWorkspace.shared.frontmostApplication
        let sourceID = application?.bundleIdentifier ?? ""
        if ["com.apple.Passwords", "com.apple.keychainaccess", "com.bitwarden.desktop",
            "com.agilebits.onepassword7", "com.lastpass.LastPass"].contains(sourceID) { return }
        let source = application?.localizedName ?? "Unknown app"
        var item: Clip?
        if let urls = board.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL],
           !urls.isEmpty, urls.count <= 40 {
            let paths = urls.map(\.path)
            item = Clip(id: UUID().uuidString, kind: "Files",
                        title: urls.count == 1 ? urls[0].lastPathComponent : "\(urls.count) files",
                        text: nil, files: paths, imageName: nil, source: source,
                        copiedAt: Date(), pinned: false)
        } else if let image = NSImage(pasteboard: board),
                  let tiff = image.tiffRepresentation,
                  let bitmap = NSBitmapImageRep(data: tiff),
                  let png = bitmap.representation(using: .png, properties: [:]),
                  png.count <= 8 * 1024 * 1024 {
            let id = UUID().uuidString
            let name = id + ".png"
            ensureFolders()
            let file = imageFolder.appendingPathComponent(name)
            if (try? png.write(to: file, options: .atomic)) != nil {
                secure(file)
                item = Clip(id: id, kind: "Images", title: "Image · \(bitmap.pixelsWide) × \(bitmap.pixelsHigh)",
                            text: nil, files: nil, imageName: name, source: source,
                            copiedAt: Date(), pinned: false)
            }
        } else if let text = board.string(forType: .string),
                  !text.isEmpty, text.utf8.count <= 64 * 1024 {
            let first = text.split(whereSeparator: \.isNewline).first.map(String.init) ?? text
            let label = String(first.prefix(100)).trimmingCharacters(in: .whitespacesAndNewlines)
            item = Clip(id: UUID().uuidString, kind: "Text",
                        title: label.isEmpty ? "Text" : label, text: text,
                        files: nil, imageName: nil, source: source,
                        copiedAt: Date(), pinned: false)
        }
        guard let item else { return }
        if let first = clips.first, !first.pinned,
           first.kind == item.kind && first.text == item.text && first.files == item.files,
           item.kind != "Images" { return }
        clips.insert(item, at: 0)
        selectedID = item.id
        trimAndSave()
    }

    func togglePin(_ clip: Clip) {
        guard let index = clips.firstIndex(where: { $0.id == clip.id }) else { return }
        if !clips[index].pinned && clips.filter(\.pinned).count >= 100 {
            notice = "You can keep up to 100 pinned clips."
            return
        }
        clips[index].pinned.toggle()
        let moved = clips.remove(at: index)
        clips.insert(moved, at: moved.pinned ? 0 : clips.firstIndex(where: { !$0.pinned }) ?? clips.count)
        save()
    }

    func delete(_ clip: Clip) {
        clips.removeAll { $0.id == clip.id }
        removeImage(clip)
        selectFirstVisible()
        save()
    }

    func clearRecent() {
        let removed = clips.filter { !$0.pinned }
        clips.removeAll { !$0.pinned }
        removed.forEach(removeImage)
        selectFirstVisible()
        save()
    }

    func image(for clip: Clip) -> NSImage? {
        guard let name = clip.imageName else { return nil }
        return NSImage(contentsOf: imageFolder.appendingPathComponent(name))
    }

    func restore(_ clip: Clip, on board: NSPasteboard = .general) -> Bool {
        if clip.kind == "Text" && clip.text == nil { return false }
        if clip.kind == "Files" {
            guard let files = clip.files, !files.isEmpty,
                  files.allSatisfy({ FileManager.default.fileExists(atPath: $0) })
            else { return false }
        }
        if clip.kind == "Images" {
            guard let name = clip.imageName,
                  FileManager.default.fileExists(atPath: imageFolder.appendingPathComponent(name).path)
            else { return false }
        }
        board.clearContents()
        let wrote: Bool
        switch clip.kind {
        case "Text": wrote = clip.text.map { board.setString($0, forType: .string) } ?? false
        case "Files":
            let urls = (clip.files ?? []).map { URL(fileURLWithPath: $0) as NSURL }
            wrote = !urls.isEmpty && board.writeObjects(urls)
        case "Images":
            if let name = clip.imageName,
               let data = try? Data(contentsOf: imageFolder.appendingPathComponent(name)) {
                wrote = board.setData(data, forType: .png)
            } else { wrote = false }
        default: wrote = false
        }
        lastChange = board.changeCount
        return wrote
    }

    private func trimAndSave() {
        let pinned = clips.filter(\.pinned)
        let recent = clips.filter { !$0.pinned }
        let retained = Array(pinned.prefix(100)) + Array(recent.prefix(300))
        let kept = Set(retained.map(\.id))
        clips.filter { !kept.contains($0.id) }.forEach(removeImage)
        clips = retained
        save()
    }

    private func removeImage(_ clip: Clip) {
        guard let name = clip.imageName else { return }
        try? FileManager.default.removeItem(at: imageFolder.appendingPathComponent(name))
    }

    private func ensureFolders() {
        try? FileManager.default.createDirectory(at: imageFolder, withIntermediateDirectories: true,
                                                  attributes: [.posixPermissions: 0o700])
    }

    private func secure(_ file: URL) {
        try? FileManager.default.setAttributes([.posixPermissions: 0o600], ofItemAtPath: file.path)
    }

    private func save() {
        ensureFolders()
        guard let data = try? encoder.encode(clips) else { return }
        do {
            try data.write(to: index, options: .atomic)
            secure(index)
        } catch {
            notice = "Could not save Clipboard History."
        }
    }
}

private enum ClipStyle {
    static let background = Color(red: 0.075, green: 0.092, blue: 0.106)
    static let surface = Color(red: 0.105, green: 0.125, blue: 0.145)
    static let elevated = Color(red: 0.155, green: 0.185, blue: 0.205)
    static let border = Color(red: 0.23, green: 0.27, blue: 0.29)
    static let accent = Color(red: 0.48, green: 0.79, blue: 0.87)
    static let text = Color(red: 0.94, green: 0.96, blue: 0.97)
    static let muted = Color(red: 0.63, green: 0.68, blue: 0.71)
}

private struct ClipPanelView: View {
    @ObservedObject var library: ClipLibrary
    let targetName: String
    let shortcut: String
    let paste: (Clip) -> Void
    let copy: (Clip) -> Void
    let close: () -> Void
    let clearRecent: () -> Void
    @FocusState private var searchFocused: Bool

    var body: some View {
        VStack(spacing: 0) {
            header
            Rectangle().fill(ClipStyle.border).frame(height: 1)
            HStack(spacing: 0) {
                list
                    .frame(width: 345)
                Rectangle().fill(ClipStyle.border).frame(width: 1)
                detail
                    .frame(maxWidth: .infinity, maxHeight: .infinity)
            }
            Rectangle().fill(ClipStyle.border).frame(height: 1)
            footer
        }
        .frame(width: 850, height: 570)
        .background(ClipStyle.background)
        .foregroundColor(ClipStyle.text)
        .preferredColorScheme(.dark)
        .onAppear { searchFocused = true }
        .onChange(of: library.query) { _ in library.selectFirstVisible() }
        .onChange(of: library.filter) { _ in library.selectFirstVisible() }
    }

    private var header: some View {
        HStack(spacing: 13) {
            Image(systemName: "doc.on.clipboard.fill")
                .font(.system(size: 18, weight: .semibold))
                .foregroundColor(ClipStyle.background)
                .frame(width: 38, height: 38)
                .background(ClipStyle.accent, in: RoundedRectangle(cornerRadius: 10))
            VStack(alignment: .leading, spacing: 2) {
                Text("Clipboard History").font(.system(size: 18, weight: .semibold))
                Text("\(library.count) saved · on this Mac")
                    .font(.system(size: 11)).foregroundColor(ClipStyle.muted)
            }
            Spacer(minLength: 12)
            HStack(spacing: 8) {
                Image(systemName: "magnifyingglass").foregroundColor(ClipStyle.muted)
                TextField("Search clips", text: $library.query)
                    .textFieldStyle(.plain)
                    .focused($searchFocused)
                    .font(.system(size: 13))
            }
            .padding(.horizontal, 12).frame(width: 210, height: 35)
            .background(ClipStyle.surface, in: RoundedRectangle(cornerRadius: 9))
            .overlay(RoundedRectangle(cornerRadius: 9).stroke(ClipStyle.border))
            Picker("Type", selection: $library.filter) {
                ForEach(["All", "Text", "Images", "Files"], id: \.self) { option in
                    Text(option == "All" ? "All types" : option).tag(option)
                }
            }
            .labelsHidden().pickerStyle(.menu).frame(width: 105)
            Button(action: close) {
                Image(systemName: "xmark").font(.system(size: 11, weight: .semibold))
                    .frame(width: 29, height: 29)
                    .background(ClipStyle.surface, in: RoundedRectangle(cornerRadius: 8))
            }
            .buttonStyle(.plain).help("Close · Esc")
        }
        .padding(.horizontal, 18).frame(height: 70)
    }

    private var list: some View {
        ScrollView {
            LazyVStack(alignment: .leading, spacing: 3) {
                if !library.pinned.isEmpty {
                    section("PINNED", count: library.pinned.count)
                    ForEach(library.pinned) { clip in row(clip) }
                    Color.clear.frame(height: 11)
                }
                section("RECENT", count: library.recent.count)
                if library.recent.isEmpty && library.pinned.isEmpty {
                    VStack(alignment: .leading, spacing: 8) {
                        Image(systemName: "doc.on.clipboard")
                            .font(.system(size: 30)).foregroundColor(ClipStyle.accent)
                        Text(library.query.isEmpty ? "Your next copy starts here" : "No matching clips")
                            .font(.system(size: 14, weight: .medium))
                        Text(library.query.isEmpty ? "Copy text, images or files in any app." : "Try another search or type filter.")
                            .font(.system(size: 12)).foregroundColor(ClipStyle.muted)
                    }
                    .padding(18).frame(maxWidth: .infinity, alignment: .leading)
                }
                ForEach(library.recent) { clip in row(clip) }
            }
            .padding(11)
        }
        .background(ClipStyle.surface)
    }

    private func section(_ title: String, count: Int) -> some View {
        HStack {
            Text(title).font(.system(size: 10, weight: .bold, design: .rounded))
                .tracking(1.1).foregroundColor(ClipStyle.muted)
            Spacer()
            Text("\(count)").font(.system(size: 10, weight: .medium))
                .foregroundColor(ClipStyle.muted)
        }
        .padding(.horizontal, 9).padding(.top, 12).padding(.bottom, 7)
    }

    private func row(_ clip: Clip) -> some View {
        let active = clip.id == library.selectedID
        return Button {
            library.selectedID = clip.id
        } label: {
            HStack(spacing: 10) {
                Image(systemName: symbol(for: clip))
                    .font(.system(size: 15, weight: .medium))
                    .foregroundColor(active ? ClipStyle.accent : ClipStyle.muted)
                    .frame(width: 20)
                VStack(alignment: .leading, spacing: 3) {
                    Text(clip.title).font(.system(size: 12.5, weight: .medium))
                        .lineLimit(1).truncationMode(.tail)
                    Text(clip.source).font(.system(size: 10.5))
                        .foregroundColor(ClipStyle.muted).lineLimit(1)
                }
                Spacer(minLength: 0)
                if clip.pinned {
                    Image(systemName: "pin.fill").font(.system(size: 10))
                        .foregroundColor(ClipStyle.accent)
                }
            }
            .padding(.horizontal, 11).frame(height: 47)
            .background(active ? ClipStyle.elevated : Color.clear,
                        in: RoundedRectangle(cornerRadius: 9))
            .contentShape(Rectangle())
        }
        .buttonStyle(.plain)
        .help(clip.title)
    }

    private var detail: some View {
        VStack(alignment: .leading, spacing: 0) {
            if let clip = library.selected {
                HStack(spacing: 9) {
                    Image(systemName: symbol(for: clip))
                        .foregroundColor(ClipStyle.accent)
                    Text(clip.kind.uppercased())
                        .tracking(1.0).font(.system(size: 10, weight: .bold))
                        .foregroundColor(ClipStyle.accent)
                    Spacer()
                    Text(clip.copiedAt, style: .relative)
                        .font(.system(size: 11)).foregroundColor(ClipStyle.muted)
                }
                .padding(.bottom, 15)
                ScrollView {
                    Group {
                        if let text = clip.text {
                            Text(text).font(.system(size: 13, design: .monospaced))
                                .textSelection(.enabled)
                                .frame(maxWidth: .infinity, alignment: .leading)
                        } else if let image = library.image(for: clip) {
                            Image(nsImage: image).resizable().scaledToFit()
                                .frame(maxWidth: .infinity, maxHeight: 270)
                        } else if let files = clip.files {
                            VStack(alignment: .leading, spacing: 9) {
                                ForEach(files, id: \.self) { file in
                                    Label(URL(fileURLWithPath: file).lastPathComponent,
                                          systemImage: "doc")
                                        .font(.system(size: 12))
                                }
                            }.frame(maxWidth: .infinity, alignment: .leading)
                        }
                    }
                    .frame(maxWidth: .infinity, alignment: .leading)
                }
                .frame(maxHeight: .infinity)
                Rectangle().fill(ClipStyle.border).frame(height: 1)
                VStack(spacing: 8) {
                    info("Copied from", clip.source)
                    info("Type", clip.kind)
                    if let text = clip.text { info("Characters", "\(text.count)") }
                    if let files = clip.files { info("Files", "\(files.count)") }
                }.padding(.vertical, 14)
                HStack(spacing: 8) {
                    action(clip.pinned ? "Unpin" : "Pin", icon: clip.pinned ? "pin.slash" : "pin") {
                        library.togglePin(clip)
                    }
                    action("Copy", icon: "doc.on.doc") { copy(clip) }
                    action("Delete", icon: "trash") { library.delete(clip) }
                    Spacer()
                    Button { paste(clip) } label: {
                        Label("Paste", systemImage: "arrow.turn.down.left")
                            .font(.system(size: 12, weight: .semibold))
                            .padding(.horizontal, 14).frame(height: 31)
                            .foregroundColor(ClipStyle.background)
                            .background(ClipStyle.accent, in: RoundedRectangle(cornerRadius: 8))
                    }.buttonStyle(.plain)
                }
            } else {
                Spacer()
                Image(systemName: "square.on.square")
                    .font(.system(size: 42, weight: .ultraLight))
                    .foregroundColor(ClipStyle.accent)
                    .frame(maxWidth: .infinity)
                Text("Choose a clip to preview")
                    .font(.system(size: 17, weight: .medium))
                    .frame(maxWidth: .infinity).padding(.top, 13)
                Spacer()
            }
        }
        .padding(20)
    }

    private func info(_ label: String, _ value: String) -> some View {
        HStack {
            Text(label).foregroundColor(ClipStyle.muted)
            Spacer()
            Text(value).lineLimit(1).truncationMode(.middle)
        }.font(.system(size: 11))
    }

    private func action(_ title: String, icon: String, perform: @escaping () -> Void) -> some View {
        Button(action: perform) {
            Label(title, systemImage: icon).font(.system(size: 11))
                .padding(.horizontal, 9).frame(height: 30)
                .background(ClipStyle.elevated, in: RoundedRectangle(cornerRadius: 7))
        }.buttonStyle(.plain)
    }

    private var footer: some View {
        HStack(spacing: 10) {
            Image(systemName: "keyboard").foregroundColor(ClipStyle.accent)
            Text(shortcut).font(.system(size: 11, weight: .medium))
            Text("to open anywhere").foregroundColor(ClipStyle.muted)
            Spacer()
            if !library.notice.isEmpty {
                Text(library.notice).foregroundColor(ClipStyle.muted).lineLimit(1)
            }
            Button("Clear recents", action: clearRecent)
                .buttonStyle(.plain).foregroundColor(ClipStyle.muted)
            Text("↩ Paste to \(targetName) · ⌘. Pin · Esc Close")
                .foregroundColor(ClipStyle.muted).lineLimit(1)
        }
        .font(.system(size: 11))
        .padding(.horizontal, 18).frame(height: 45)
        .background(ClipStyle.surface)
    }

    private func symbol(for clip: Clip) -> String {
        switch clip.kind {
        case "Images": return "photo"
        case "Files": return "doc.on.doc"
        default: return "text.alignleft"
        }
    }
}

private final class ClipboardBridge {
    private let parentPID: pid_t
    private let library: ClipLibrary
    private var shortcut: String
    private var hotkey: EventHotKeyRef?
    private var handler: EventHandlerRef?
    private var panel: NSPanel?
    private var localKeys: Any?
    private var target: NSRunningApplication?

    init(parentPID: pid_t, shortcut: String) {
        self.parentPID = parentPID
        self.shortcut = shortcut
        let folder = ProcessInfo.processInfo.environment["POLYMATH_CLIPBOARD_DIR"].map(URL.init(fileURLWithPath:))
            ?? FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask)[0]
                .appendingPathComponent("Polymath/Clipboard History", isDirectory: true)
        library = ClipLibrary(folder: folder)
    }

    func run() {
        let application = NSApplication.shared
        application.setActivationPolicy(.accessory)
        application.finishLaunching()
        installHotkey(shortcut)
        readCommands()
        Timer.scheduledTimer(withTimeInterval: 0.7, repeats: true) { [weak self] _ in
            guard let self else { return }
            if self.parentPID > 0 && kill(self.parentPID, 0) != 0 {
                self.shutdown()
                return
            }
            self.library.capture()
        }
        application.run()
    }

    private func send(_ message: String) {
        let object = ["kind": "status", "text": message]
        guard let data = try? JSONSerialization.data(withJSONObject: object),
              let line = String(data: data, encoding: .utf8) else { return }
        FileHandle.standardOutput.write(Data((line + "\n").utf8))
    }

    private func readCommands() {
        DispatchQueue.global(qos: .utility).async { [weak self] in
            while let line = readLine() {
                guard let data = line.data(using: .utf8),
                      let command = try? JSONSerialization.jsonObject(with: data) as? [String: Any]
                else { continue }
                DispatchQueue.main.async {
                    guard let self else { return }
                    if command["quit"] as? Bool == true { self.shutdown(); return }
                    if command["show"] as? Bool == true { self.show(); return }
                    if let shortcut = command["shortcut"] as? String {
                        self.installHotkey(shortcut)
                    }
                }
            }
            DispatchQueue.main.async { self?.shutdown() }
        }
    }

    private func installHotkey(_ requested: String) {
        guard let (code, modifiers, display) = Self.parse(requested) else {
            send("Choose a shortcut with ⌘, ⌥ or ⌃ and one letter or number.")
            return
        }
        if let hotkey { UnregisterEventHotKey(hotkey) }
        hotkey = nil
        if handler == nil {
            var type = EventTypeSpec(eventClass: OSType(kEventClassKeyboard),
                                     eventKind: UInt32(kEventHotKeyPressed))
            let pointer = Unmanaged.passUnretained(self).toOpaque()
            let result = InstallEventHandler(GetApplicationEventTarget(), clipboardHotkeyHandler,
                                             1, &type, pointer, &handler)
            if result != noErr {
                send("Could not watch the clipboard shortcut (macOS error \(result)).")
                return
            }
        }
        var registered: EventHotKeyRef?
        let identity = EventHotKeyID(signature: 0x50434C50, id: 1)
        let result = RegisterEventHotKey(code, modifiers, identity,
                                         GetApplicationEventTarget(), 0, &registered)
        guard result == noErr, let registered else {
            send("\(display) is already used by another app. Choose another shortcut in Settings.")
            return
        }
        hotkey = registered
        shortcut = requested
        send("Ready · press \(display) anywhere")
    }

    private static func parse(_ text: String) -> (UInt32, UInt32, String)? {
        let parts = text.lowercased().split(separator: "+").map(String.init)
        guard let key = parts.last, parts.count >= 2 else { return nil }
        let modifiers = Set(parts.dropLast())
        guard modifiers.isSubset(of: ["cmd", "option", "ctrl", "shift"]),
              modifiers.contains("cmd") || modifiers.contains("option") || modifiers.contains("ctrl")
        else { return nil }
        let codes: [String: UInt32] = [
            "a":0, "s":1, "d":2, "f":3, "h":4, "g":5, "z":6, "x":7, "c":8, "v":9,
            "b":11, "q":12, "w":13, "e":14, "r":15, "y":16, "t":17, "1":18, "2":19,
            "3":20, "4":21, "6":22, "5":23, "9":25, "7":26, "8":28, "0":29,
            "o":31, "u":32, "i":34, "p":35, "l":37, "j":38, "k":40, "n":45, "m":46
        ]
        guard let code = codes[key] else { return nil }
        var carbon: UInt32 = 0
        var display = ""
        if modifiers.contains("ctrl") { carbon |= UInt32(controlKey); display += "⌃" }
        if modifiers.contains("option") { carbon |= UInt32(optionKey); display += "⌥" }
        if modifiers.contains("shift") { carbon |= UInt32(shiftKey); display += "⇧" }
        if modifiers.contains("cmd") { carbon |= UInt32(cmdKey); display += "⌘" }
        display += key.uppercased()
        return (code, carbon, display)
    }

    fileprivate func toggle() {
        if panel?.isVisible == true { close() } else { show() }
    }

    private func show() {
        library.capture()
        library.query = ""
        library.filter = "All"
        library.selectFirstVisible()
        let front = NSWorkspace.shared.frontmostApplication
        if front?.processIdentifier != getpid() { target = front }
        let name = target?.localizedName ?? "previous app"
        let display = Self.parse(shortcut)?.2 ?? "⌘D"
        let view = ClipPanelView(library: library, targetName: name, shortcut: display,
                                 paste: { [weak self] in self?.paste($0) },
                                 copy: { [weak self] in self?.copy($0) },
                                 close: { [weak self] in self?.close() },
                                 clearRecent: { [weak self] in self?.confirmClear() })
        if panel == nil {
            let window = NSPanel(contentRect: NSRect(x: 0, y: 0, width: 850, height: 570),
                                 styleMask: [.titled, .fullSizeContentView, .utilityWindow],
                                 backing: .buffered, defer: false)
            window.title = "Polymath Clipboard History"
            window.titleVisibility = .hidden
            window.titlebarAppearsTransparent = true
            window.isMovableByWindowBackground = true
            window.isReleasedWhenClosed = false
            window.level = .floating
            window.collectionBehavior = [.canJoinAllSpaces, .fullScreenAuxiliary]
            window.backgroundColor = NSColor(red: 0.075, green: 0.092, blue: 0.106, alpha: 1)
            window.hasShadow = true
            panel = window
        }
        panel?.contentView = NSHostingView(rootView: view)
        panel?.center()
        panel?.makeKeyAndOrderFront(nil)
        NSApp.activate(ignoringOtherApps: true)
        if localKeys == nil {
            localKeys = NSEvent.addLocalMonitorForEvents(matching: .keyDown) { [weak self] event in
                guard let self, self.panel?.isVisible == true else { return event }
                switch event.keyCode {
                case 53: self.close(); return nil
                case 36:
                    if let clip = self.library.selected { self.paste(clip) }
                    return nil
                case 125: self.library.moveSelection(1); return nil
                case 126: self.library.moveSelection(-1); return nil
                case 47 where event.modifierFlags.contains(.command):
                    if let clip = self.library.selected { self.library.togglePin(clip) }
                    return nil
                default: return event
                }
            }
        }
    }

    private func close() {
        panel?.orderOut(nil)
        target?.activate(options: [])
    }

    private func copy(_ clip: Clip) {
        library.notice = library.restore(clip) ? "Copied" : "This clip is unavailable"
    }

    private func paste(_ clip: Clip) {
        guard library.restore(clip) else {
            library.notice = "This clip is unavailable"
            return
        }
        let destination = target
        panel?.orderOut(nil)
        destination?.activate(options: [])
        guard AXIsProcessTrusted() else {
            send("Copied · allow Accessibility for automatic paste, or press ⌘V")
            return
        }
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.16) {
            guard let down = CGEvent(keyboardEventSource: nil, virtualKey: 9, keyDown: true),
                  let up = CGEvent(keyboardEventSource: nil, virtualKey: 9, keyDown: false)
            else { return }
            down.flags = .maskCommand
            up.flags = .maskCommand
            down.post(tap: .cghidEventTap)
            up.post(tap: .cghidEventTap)
        }
    }

    private func confirmClear() {
        let alert = NSAlert()
        alert.messageText = "Clear recent clips?"
        alert.informativeText = "Pinned clips will stay. This cannot be undone."
        alert.addButton(withTitle: "Clear recents")
        alert.addButton(withTitle: "Cancel")
        if alert.runModal() == .alertFirstButtonReturn { library.clearRecent() }
    }

    private func shutdown() {
        if let hotkey { UnregisterEventHotKey(hotkey) }
        if let handler { RemoveEventHandler(handler) }
        if let localKeys { NSEvent.removeMonitor(localKeys) }
        NSApp.stop(nil)
        exit(0)
    }

    static func selfTest() -> Bool {
        let folder = FileManager.default.temporaryDirectory
            .appendingPathComponent("polymath-clipboard-test-\(UUID().uuidString)")
        defer { try? FileManager.default.removeItem(at: folder) }
        let board = NSPasteboard.withUniqueName()
        let first = ClipLibrary(folder: folder, pasteboard: board)
        board.clearContents()
        board.setString("first note", forType: .string)
        first.capture(board)
        guard let clip = first.selected, first.count == 1 else { return false }
        first.togglePin(clip)
        let loaded = ClipLibrary(folder: folder, pasteboard: board)
        guard loaded.pinned.count == 1, let pinned = loaded.pinned.first else { return false }
        let restored = NSPasteboard.withUniqueName()
        guard loaded.restore(pinned, on: restored),
              restored.string(forType: .string) == "first note" else { return false }
        loaded.clearRecent()
        guard loaded.pinned.count == 1 else { return false }

        let file = folder.appendingPathComponent("example.txt")
        try? "file".write(to: file, atomically: true, encoding: .utf8)
        board.clearContents()
        guard board.writeObjects([file as NSURL]) else { return false }
        loaded.capture(board)
        guard let fileClip = loaded.selected, fileClip.kind == "Files" else { return false }
        loaded.togglePin(fileClip)

        guard let bitmap = NSBitmapImageRep(bitmapDataPlanes: nil, pixelsWide: 2,
                                            pixelsHigh: 2, bitsPerSample: 8,
                                            samplesPerPixel: 4, hasAlpha: true,
                                            isPlanar: false, colorSpaceName: .deviceRGB,
                                            bytesPerRow: 8, bitsPerPixel: 32),
              let png = bitmap.representation(using: .png, properties: [:])
        else { return false }
        board.clearContents()
        board.setData(png, forType: .png)
        loaded.capture(board)
        guard let imageClip = loaded.selected, imageClip.kind == "Images" else { return false }
        loaded.togglePin(imageClip)

        let reloaded = ClipLibrary(folder: folder, pasteboard: board)
        let imageBoard = NSPasteboard.withUniqueName()
        return reloaded.pinned.count == 3
            && reloaded.restore(imageClip, on: imageBoard)
            && imageBoard.data(forType: .png) != nil
    }
}

private func clipboardHotkeyHandler(_ next: EventHandlerCallRef?, _ event: EventRef?,
                                    _ pointer: UnsafeMutableRawPointer?) -> OSStatus {
    guard let pointer else { return OSStatus(eventNotHandledErr) }
    let bridge = Unmanaged<ClipboardBridge>.fromOpaque(pointer).takeUnretainedValue()
    bridge.toggle()
    return noErr
}

func runPolymathClipboard(parentPID: pid_t, shortcut: String) {
    ClipboardBridge(parentPID: parentPID, shortcut: shortcut).run()
}

func testPolymathClipboard() -> Bool { ClipboardBridge.selfTest() }
